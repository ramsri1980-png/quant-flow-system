#!/usr/bin/env python3
"""Regenerate openspec/modules.md from src/quantflow/ and openspec/specs/.

Format: path | purpose (first docstring line) | public API
Regenerate after each feature merge. Do not edit modules.md by hand.
"""
from __future__ import annotations
from pathlib import Path
import ast
import sys

ROOT = Path(__file__).resolve().parents[1]
SRC = ROOT / "src" / "quantflow"
SPECS = ROOT / "openspec" / "specs"
OUT = ROOT / "openspec" / "modules.md"


def public_api(tree: ast.Module) -> list[str]:
    names = []
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef, ast.ClassDef)):
            if not node.name.startswith("_"):
                names.append(node.name)
    return names


def first_line(doc: str | None) -> str:
    if not doc:
        return "(no docstring)"
    return doc.strip().split("\n", 1)[0]


def scan_python() -> list[str]:
    lines: list[str] = []
    if not SRC.exists():
        return lines
    for py in sorted(SRC.rglob("*.py")):
        rel_parts = py.relative_to(SRC).parts
        if py.name == "__init__.py" or "test" in rel_parts:
            continue
        try:
            tree = ast.parse(py.read_text())
        except SyntaxError:
            lines.append(f"- `{py.relative_to(SRC)}` | (syntax error — skipped) | —")
            continue
        doc = first_line(ast.get_docstring(tree))
        api = public_api(tree)
        shown = ", ".join(api[:6]) + ("..." if len(api) > 6 else "")
        lines.append(f"- `{py.relative_to(SRC)}` | {doc} | {shown or '—'}")
    return lines


def scan_specs() -> list[str]:
    lines: list[str] = []
    if not SPECS.exists():
        return lines
    for spec in sorted(SPECS.rglob("*.md")):
        rel = spec.relative_to(SPECS)
        text = spec.read_text()
        title = next((l.lstrip("# ").strip() for l in text.splitlines() if l.startswith("#")), rel.name)
        lines.append(f"- `specs/{rel}` | {title} | —")
    return lines


def main() -> int:
    header = [
        "# Reusable Modules Index",
        "",
        "Auto-generated by `scripts/gen_modules_index.py`.",
        "Do not edit by hand. Regenerate after each feature merge:",
        "",
        "```bash",
        "python3 scripts/gen_modules_index.py",
        "```",
        "",
        "Used by `/qf-propose` and `/qf-apply` to enforce reuse-first.",
        "",
        "## Python modules (`src/quantflow/`)",
        "",
    ]
    body = scan_python() or ["- (none yet — src/quantflow/ is empty)"]
    specs_header = ["", "## OpenSpec capabilities (`openspec/specs/`)", ""]
    specs_body = scan_specs() or ["- (none yet)"]

    OUT.parent.mkdir(parents=True, exist_ok=True)
    OUT.write_text("\n".join(header + body + specs_header + specs_body) + "\n")
    n_py = len([l for l in body if l.startswith("- `")])
    n_spec = len([l for l in specs_body if l.startswith("- `")])
    print(f"wrote {OUT}: {n_py} python modules, {n_spec} specs")
    return 0


if __name__ == "__main__":
    sys.exit(main())
