"""Regenerate openspec/modules.md -- the reuse-first module index.

Scans src/quantflow/ for Python modules and openspec/specs/ for capability
directories, and writes the index consumed by /opsx-propose and /opsx-apply
(reuse-first rule: extend/compose existing modules before creating new ones).

Usage: python3 scripts/gen_modules_index.py
"""

import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
SRC_ROOT = REPO_ROOT / "src" / "quantflow"
SPECS_DIR = REPO_ROOT / "openspec" / "specs"
OUTPUT = REPO_ROOT / "openspec" / "modules.md"


def python_modules(src_root: Path = SRC_ROOT) -> list[str]:
    """Dotted module paths under src/quantflow (packages and files)."""
    if not src_root.exists():
        return []
    return sorted(
        ".".join(path.relative_to(src_root.parent).with_suffix("").parts)
        for path in src_root.rglob("*.py")
        if "__pycache__" not in path.parts and path.name != "__init__.py"
    )


def capabilities(specs_dir: Path = SPECS_DIR) -> list[str]:
    """Capability directories under openspec/specs (added at archive time)."""
    if not specs_dir.exists():
        return []
    return sorted(entry.name for entry in specs_dir.iterdir() if entry.is_dir())


def render(modules: list[str], caps: list[str]) -> str:
    """Render modules.md deterministically."""
    module_lines = "\n".join(f"- {name}" for name in modules) or "- (none yet)"
    cap_lines = "\n".join(f"- {name}" for name in caps) or "- (none yet)"
    return (
        "# Reusable Modules Index\n"
        "\n"
        "Auto-generated by `scripts/gen_modules_index.py`.\n"
        "Do not edit by hand. Regenerate after each feature merge:\n"
        "\n"
        "```bash\n"
        "python3 scripts/gen_modules_index.py\n"
        "```\n"
        "\n"
        "Used by `/opsx-propose` and `/opsx-apply` to enforce reuse-first.\n"
        "\n"
        "## Python modules (`src/quantflow/`)\n"
        "\n"
        f"{module_lines}\n"
        "\n"
        "## OpenSpec capabilities (`openspec/specs/`)\n"
        "\n"
        f"{cap_lines}\n"
    )


def main() -> int:
    """Write openspec/modules.md."""
    OUTPUT.write_text(render(python_modules(), capabilities()))
    print(f"wrote {OUTPUT}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
